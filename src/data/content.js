export function formatWeddingDate(dateISO, lang) {
  const d = new Date(dateISO)
  if (lang === 'km') {
    const days = ['អាទិត្យ', 'ច័ន្ទ', 'អង្គារ', 'ពុធ', 'ព្រហស្បតិ៍', 'សុក្រ', 'សៅរ៍']
    const months = [
      'មករា',
      'កុម្ភៈ',
      'មីនា',
      'មេសា',
      'ឧសភា',
      'មិថុនា',
      'កក្កដា',
      'សីហា',
      'កញ្ញា',
      'តុលា',
      'វិច្ឆិកា',
      'ធ្នូ',
    ]
    const toKhmerNum = (n) =>
      String(n).replace(/\d/g, (digit) => '០១២៣៤៥៦៧៨៩'[Number(digit)])
    return `ថ្ងៃ${days[d.getDay()]} · ${toKhmerNum(d.getDate())} ${months[d.getMonth()]} ${d.getFullYear()}`
  }
  return d.toLocaleDateString('en-GB', {
    weekday: 'long',
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  })
}

export function formatWeddingDateTime(dateISO, lang) {
  const d = new Date(dateISO)
  const date = formatWeddingDate(dateISO, lang)
  const time = d.toLocaleTimeString(lang === 'km' ? 'en-GB' : 'en-US', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  })
  return `${date} · ${time}`
}

export function googleCalendarUrl(dateISO, title, location) {
  const start = new Date(dateISO)
  const end = new Date(start.getTime() + 4 * 60 * 60 * 1000)
  const fmt = (dt) =>
    dt.toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '')
  const params = new URLSearchParams({
    action: 'TEMPLATE',
    text: title,
    dates: `${fmt(start)}/${fmt(end)}`,
    location,
  })
  return `https://calendar.google.com/calendar/render?${params.toString()}`
}

export function icsBlobUrl(dateISO, title, location) {
  const start = new Date(dateISO)
  const end = new Date(start.getTime() + 4 * 60 * 60 * 1000)
  const fmt = (dt) =>
    dt.toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '')
  const ics = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'BEGIN:VEVENT',
    `DTSTART:${fmt(start)}`,
    `DTEND:${fmt(end)}`,
    `SUMMARY:${title}`,
    `LOCATION:${location}`,
    'END:VEVENT',
    'END:VCALENDAR',
  ].join('\n')
  return URL.createObjectURL(new Blob([ics], { type: 'text/calendar' }))
}
